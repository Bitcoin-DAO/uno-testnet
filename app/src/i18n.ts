export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const dict = getState().lang === 'en' ? en : it;
  return dict[key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export const fmtSats = (n: number) => new Intl.NumberFormat(getState().lang === 'en' ? 'en-GB' : 'it-IT').format(n);

export const fmtDate = (unix: number, withYear = true) =>
  new Intl.DateTimeFormat(getState().lang === 'en' ? 'en-GB' : 'it-IT', {
    day: 'numeric',
    month: 'short',
    ...(withYear ? { year: 'numeric' } : {}),
  }).format(new Date(unix * 1000));

export function fmtLeft(seconds: number): string {
  if (seconds >= 2 * 86400) return t('time.days', { n: Math.floor(seconds / 86400) });
  if (seconds >= 86400) return t('time.day');
  if (seconds >= 3600) return t('time.hours', { n: Math.floor(seconds / 3600) });
  return t('time.minutes', { n: Math.max(1, Math.ceil(seconds / 60)) });
}

export const fmtDateTime = (unix: number) =>
  new Intl.DateTimeFormat(getState().lang === 'en' ? 'en-GB' : 'it-IT', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' }).format(new Date(unix * 1000));
